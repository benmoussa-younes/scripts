#!/usr/bin/env sh
# tools/scripts/binaries/version.sh — single project version, computed from git.
#
# Single source of truth used by:
#   * the MSBuild build (Directory.Build.targets -> generates obj/Generated/BuildVersion.g.cs);
#   * packaging/build-deb.sh and packaging/smoke-test.sh;
#   * any tool that must read the version without compiling.
#
# Scheme (SemVer derived from `git describe --tags`):
#   * tag `vX.Y.Z` ancestor of HEAD, HEAD on the tag        -> X.Y.Z
#   * tag `vX.Y.Z` ancestor, N commits ahead                -> X.Y.Z+N.<hash>
#   * no tag in the repository (an untagged clone)          -> 0.1.0+build.<hash>
#   * modified working tree                                 -> …_dirty
#   * git or repository unavailable                         -> 0.1.0 (fallback)
#
# The « + » separator is a SemVer build metadata (ignored by
# Debian version comparisons, which use the X.Y.Z part alone).
#
# « Dirty » (modified) = a TRACKED file is modified, like `git describe --dirty`.
# Untracked files are ignored. The artifacts generated
# by the build itself (`packaging/SHA256SUMS`) are also ignored, otherwise a build would make the tree
# dirty and change the version of the next binary — which would break the
# bit-for-bit reproducibility of the package (.deb) between two identical builds.
#
# Usage: tools/scripts/binaries/version.sh
set -eu

# Repository root = parent of this script's folder.
script_directory="$(cd "$(dirname "$0")" && pwd)"
repository_root="$(cd "$script_directory/../../.." && pwd)"

fallback="0.1.0"

# A source release archive carries the version it was cut from: without git, the archive must still
# report its own version instead of a hard-coded fallback (release audit M10).
if [ -f "$repository_root/VERSION" ]; then
    cat "$repository_root/VERSION"
    exit 0
fi

if ! command -v git >/dev/null 2>&1; then
    printf '%s\n' "$fallback"
    exit 0
fi

# Description without the `-dirty` suffix (we compute dirtiness ourselves, cf. note).
describe="$(git -C "$repository_root" describe --tags --always --long 2>/dev/null || true)"

if [ -z "$describe" ]; then
    printf '%s\n' "$fallback"
    exit 0
fi

# Dirtiness: a TRACKED file is modified, excluding build artifacts.
# (`packaging/SHA256SUMS` is regenerated by every build: ignoring it here keeps the
# version — and therefore the package — stable from one build to the next.)
# A plain shell loop (no awk, no `head`) reads the whole status stream, so parallel calls
# never trigger SIGPIPE (« Broken pipe ») and a minimal PATH is enough.
dirty=""
changed="$(git -C "$repository_root" status --porcelain --untracked-files=no 2>/dev/null || true)"
while IFS= read -r line; do
    [ -n "$line" ] || continue
    # Porcelain v1: "XY path"; a rename is "XY old -> new".
    path="${line#???}"
    case "$path" in
        *" -> "*) path="${path##* -> }" ;;
    esac
    case "$path" in
        packaging/SHA256SUMS|packaging/tarballs.sha256|packaging/SHA256SUMS.asc|packaging/tarballs.sha256.asc)
            continue
            ;;
    esac
    dirty="_dirty"
    break
done <<EOF
$changed
EOF

# <tag>-<n>-g<hash>: git describe found a tag.
case "$describe" in
    v[0-9]*.*.*-[0-9]*-g[0-9a-f]*)
        tag="${describe%%-*}"
        rest="${describe#*-}"
        commits="${rest%%-*}"
        rest="${rest#*-}"
        hash="${rest#g}"
        base_version="${tag#v}"
        if [ "$commits" = "0" ]; then
            printf '%s%s\n' "$base_version" "$dirty"
        else
            printf '%s+%s.%s%s\n' "$base_version" "$commits" "$hash" "$dirty"
        fi
        exit 0
        ;;
esac

# Otherwise: no tag (describe = <hash>) or unexpected format -> fallback.
printf '%s+build.%s%s\n' "$fallback" "$describe" "$dirty"
