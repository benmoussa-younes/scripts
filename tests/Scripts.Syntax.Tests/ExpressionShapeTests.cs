namespace Scripts.Syntax.Tests;

public sealed class ExpressionShapeTests
{
    [Theory]
    [InlineData("1 + 2 * 3", "(+ 1 (* 2 3))")]
    [InlineData("1 * 2 + 3", "(+ (* 1 2) 3)")]
    [InlineData("1 - 2 - 3", "(- (- 1 2) 3)")]
    [InlineData("8 / 4 / 2", "(/ (/ 8 4) 2)")]
    [InlineData("7 % 3 * 2", "(* (% 7 3) 2)")]
    [InlineData("a-b", "(- a b)")]
    [InlineData("-9223372036854775807 - 1", "(- (neg 9223372036854775807) 1)")]
    [InlineData("a - -b", "(- a (neg b))")]
    [InlineData("5--3", "(- 5 (neg 3))")]
    [InlineData("-a * b", "(* (neg a) b)")]
    [InlineData("- - a", "(neg (neg a))")]
    [InlineData("-a.b", "(neg (. a b))")]
    [InlineData("-f(x)", "(neg (call f x))")]
    [InlineData("(1 + 2) * 3", "(* (+ 1 2) 3)")]
    [InlineData("((a))", "a")]
    [InlineData("a == b", "(== a b)")]
    [InlineData("a != b", "(!= a b)")]
    [InlineData("a < b", "(< a b)")]
    [InlineData("a <= b", "(<= a b)")]
    [InlineData("a > b", "(> a b)")]
    [InlineData("a >= b", "(>= a b)")]
    [InlineData("a + 1 == b * 2", "(== (+ a 1) (* b 2))")]
    [InlineData("(a < b) < c", "(< (< a b) c)")]
    [InlineData("not a", "(not a)")]
    [InlineData("not a == b", "(not (== a b))")]
    [InlineData("not not a", "(not (not a))")]
    [InlineData("a and not b", "(and a (not b))")]
    [InlineData("not a and b", "(and (not a) b)")]
    [InlineData("a and b and c", "(and (and a b) c)")]
    [InlineData("a or b or c", "(or (or a b) c)")]
    [InlineData("(a and b) or c", "(or (and a b) c)")]
    [InlineData("a or (b and c)", "(or a (and b c))")]
    [InlineData("a == b and c < d", "(and (== a b) (< c d))")]
    [InlineData("a or not b", "(or a (not b))")]
    [InlineData("a and (b or c) and d", "(and (and a (or b c)) d)")]
    public void Operators_follow_the_precedence_table(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("a.b", "(. a b)")]
    [InlineData("a.b.c", "(. (. a b) c)")]
    [InlineData("f()", "(call f)")]
    [InlineData("f(1, 2)", "(call f 1 2)")]
    [InlineData("f(1, 2,)", "(call f 1 2)")]
    [InlineData("f(a = 1, b = 2)", "(call f (= a 1) (= b 2))")]
    [InlineData("f(a = 1, b = 2,)", "(call f (= a 1) (= b 2))")]
    [InlineData("a.b(c = 1)", "(call (. a b) (= c 1))")]
    [InlineData("a.b(c)", "(call (. a b) c)")]
    [InlineData("xs[0]", "(idx xs 0)")]
    [InlineData("xs[0][1]", "(idx (idx xs 0) 1)")]
    [InlineData("a.b(c)[d]?", "(? (idx (call (. a b) c) d))")]
    [InlineData("f()?", "(? (call f))")]
    [InlineData("f()??", "(? (? (call f)))")]
    [InlineData("f()(1)", "(call (call f) 1)")]
    [InlineData("(f)(x)", "(call f x)")]
    [InlineData("alias.f(x)", "(call (. alias f) x)")]
    [InlineData("environment.get_variable(\"A\")", "(call (. environment get_variable) \"A\")")]
    [InlineData("process.find_program_path(\"ps\")?.standard_output.lines()", "(call (. (. (? (call (. process find_program_path) \"ps\")) standard_output) lines))")]
    [InlineData("1.length", "(. 1 length)")]
    [InlineData("\"a\".length()", "(call (. \"a\" length))")]
    [InlineData("[1, 2].length()", "(call (. (list 1 2) length))")]
    public void Postfix_operators_chain_to_the_left(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("42", "42")]
    [InlineData("0xFF", "255")]
    [InlineData("1_000", "1000")]
    [InlineData("1.5", "1.5")]
    [InlineData("3.0", "3.0")]
    [InlineData("true", "true")]
    [InlineData("false", "false")]
    [InlineData("-1", "(neg 1)")]
    [InlineData("\"a\"", "\"a\"")]
    [InlineData("\"\"", "\"\"")]
    [InlineData("\"a\\nb\"", "\"a\\nb\"")]
    [InlineData("r\"a{b}\"", "\"a{b}\"")]
    [InlineData("r\"\\\"", "\"\\\\\"")]
    [InlineData("r\"\"\"a\nb\"\"\"", "\"a\\nb\"")]
    [InlineData("r\"\"\"a\"b\"\"c\"\"\"", "\"a\\\"b\\\"\\\"c\"")]
    [InlineData("p\"a\"", "(path \"a\")")]
    [InlineData("p\"\"", "(path \"\")")]
    [InlineData("\"a{x}b{y + 1}\"", "(interp \"a\" {x} \"b\" {(+ y 1)})")]
    [InlineData("\"{f(\"x{y}\")}\"", "(interp {(call f (interp \"x\" {y}))})")]
    [InlineData("\"{xs[0]}\"", "(interp {(idx xs 0)})")]
    [InlineData("\"{path.join(p, \"x\")}\"", "(interp {(call (. path join) p \"x\")})")]
    [InlineData("\"{(1)}\"", "(interp {1})")]
    [InlineData("\"{1 + 1}\"", "(interp {(+ 1 1)})")]
    [InlineData("\"{ {\"k\": 1}[\"k\"] }\"", "(interp {(idx (map (\"k\" 1)) \"k\")})")]
    [InlineData("\"{a}{b}\"", "(interp {a} {b})")]
    [InlineData("\"\\{a\\}\"", "\"{a}\"")]
    [InlineData("\"{match x { 1 => \"a\", _ => \"b\" }}\"", "(interp {(match x (1 => \"a\") (_ => \"b\"))})")]
    public void Literals_and_strings(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("[]", "(list)")]
    [InlineData("[1, 2, 3]", "(list 1 2 3)")]
    [InlineData("[1, 2,]", "(list 1 2)")]
    [InlineData("[[1], [2, 3]]", "(list (list 1) (list 2 3))")]
    [InlineData("[\n    1,\n    2,\n]", "(list 1 2)")]
    [InlineData("{}", "(map)")]
    [InlineData("{\"a\": 1}", "(map (\"a\" 1))")]
    [InlineData("{\"a\": 1, \"b\": 2,}", "(map (\"a\" 1) (\"b\" 2))")]
    [InlineData("{(1): \"x\"}", "(map (1 \"x\"))")]
    [InlineData("{\"a\": {\"b\": 2}}", "(map (\"a\" (map (\"b\" 2))))")]
    [InlineData("{\n    \"a\": 1,\n    \"b\": [1,\n        2],\n}", "(map (\"a\" 1) (\"b\" (list 1 2)))")]
    [InlineData("{k: v}", "(map (k v))")]
    [InlineData("{n: integer => n}", "(map (n (lambda (integer) n)))")]
    [InlineData("ok(1)", "(ok 1)")]
    [InlineData("ok()", "(ok)")]
    [InlineData("error(\"x\")", "(error \"x\")")]
    [InlineData("ok(ok(1))", "(ok (ok 1))")]
    [InlineData("error(ok())", "(error (ok))")]
    [InlineData("ok", "ok")]
    [InlineData("environment", "environment")]
    public void Lists_maps_and_result_constructors(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("x => x + 1", "(lambda (x) (+ x 1))")]
    [InlineData("_ => 0", "(lambda (_) 0)")]
    [InlineData("(a, b) => a + b", "(lambda (a b) (+ a b))")]
    [InlineData("() => 1", "(lambda () 1)")]
    [InlineData("(x) => x", "(lambda (x) x)")]
    [InlineData("(x: integer) => x", "(lambda (x:integer) x)")]
    [InlineData("(a, b: string) => a", "(lambda (a b:string) a)")]
    [InlineData("(_, y: integer) => y", "(lambda (_ y:integer) y)")]
    // S20: annotated wildcard parameters, including several `_`, are accepted (same rule as functions).
    [InlineData("(_: integer) => 1", "(lambda (_:integer) 1)")]
    [InlineData("(_: integer, _: integer) => 1", "(lambda (_:integer _:integer) 1)")]
    [InlineData("a => b => a + b", "(lambda (a) (lambda (b) (+ a b)))")]
    [InlineData("(x) => (y) => x", "(lambda (x) (lambda (y) x))")]
    [InlineData("x => f(x)", "(lambda (x) (call f x))")]
    [InlineData("x => x + 1 == 2", "(lambda (x) (== (+ x 1) 2))")]
    [InlineData("xs.filter(x => x > 1)", "(call (. xs filter) (lambda (x) (> x 1)))")]
    [InlineData("xs.fold(0, (acc, x) => acc + x)", "(call (. xs fold) 0 (lambda (acc x) (+ acc x)))")]
    [InlineData("(g: function(integer) -> integer) => g", "(lambda (g:function(integer)->integer) g)")]
    [InlineData("(x + 1)", "(+ x 1)")]
    [InlineData("(x)", "x")]
    [InlineData("(xs.length() + 1) * 2", "(* (+ (call (. xs length)) 1) 2)")]
    [InlineData("f((a, b) => a, 1)", "(call f (lambda (a b) a) 1)")]
    [InlineData("[x => x, y => y]", "(list (lambda (x) x) (lambda (y) y))")]
    public void Lambdas_and_parenthesized_expressions(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("xs.lines().filter(l => l.contains(\"n\"))", "(call (. (call (. xs lines)) filter) (lambda (l) (call (. l contains) \"n\")))")]
    [InlineData("x.filter(l => l.contains(\"n\")).length()", "(call (. (call (. x filter) (lambda (l) (call (. l contains) \"n\"))) length))")]
    public void Method_chains_call_their_receiver(string expression, string expected) => Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("match x { 1 => \"a\"\n _ => \"b\" }", "(match x (1 => \"a\") (_ => \"b\"))")]
    [InlineData("match x {\n    1 => \"a\"\n    _ => \"b\"\n}", "(match x (1 => \"a\") (_ => \"b\"))")]
    [InlineData("match x { 1 => \"a\", _ => \"b\" }", "(match x (1 => \"a\") (_ => \"b\"))")]
    [InlineData("match x { 1 | 2 => 1\n -1 => 2\n _ => 3 }", "(match x ((alt 1 2) => 1) (-1 => 2) (_ => 3))")]
    [InlineData("match s { \"a\" | \"b\" => 1\n n => 2 }", "(match s ((alt \"a\" \"b\") => 1) (n => 2))")]
    [InlineData("match b { true | false => 1 }", "(match b ((alt true false) => 1))")]
    [InlineData("match r { ok(v) => v\n error(_) => 0 }", "(match r ((ok v) => v) ((error _) => 0))")]
    [InlineData("match x { _ | 0 => 1 }", "(match x ((alt _ 0) => 1))")]
    [InlineData("match x { _ => ({\"a\": 1})\n }", "(match x (_ => (map (\"a\" 1))))")]
    [InlineData("match x { _ => ({}) }", "(match x (_ => (map)))")]
    [InlineData("f(match x { _ => 1 }, 2)", "(call f (match x (_ => 1)) 2)")]
    [InlineData("match x { _ => match y { _ => 1 } }", "(match x (_ => (match y (_ => 1))))")]
    [InlineData("match f(1) { _ => 1 }", "(match (call f 1) (_ => 1))")]
    public void Match_in_expression_position_has_expression_arms(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));

    [Theory]
    [InlineData("match x {\n    1 => {\n        let y = 2\n        y + 1\n    }\n    _ => 0\n}", "(match x (1 => (block (let y 2) (expr (+ y 1)))) (_ => 0))")]
    [InlineData("match x { _ => { } }", "(match x (_ => (block)))")]
    [InlineData("match x {\n    _ => {\n        match y {\n            _ => {\n                \"a\"\n            }\n        }\n    }\n}", "(match x (_ => (block (expr (match y (_ => (block (expr \"a\"))))))))")]
    [InlineData("match x {\n    _ => {\n        match y {\n            _ => f()\n        }\n        1\n    }\n}", "(match x (_ => (block (expr (match-statement y (_ => (call f)))) (expr 1))))")]
    public void Match_in_expression_position_has_block_arms_whose_last_line_is_the_value(string expression, string expected) =>
        Assert.Equal(expected, Parsing.PrintExpression(expression));
}
